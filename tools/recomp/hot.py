#!/usr/bin/env python3
"""Hot code layout: the generated functions the game calls most, placed together.

The recompiled code is about 15 MB of ARM code (one section per function,
-ffunction-sections) in the order of the guest addresses, so the few hundred
functions a frame runs are spread over all of it: on the console each call of a
cold neighbour costs instruction cache and TLB misses. This writes a linker
section ordering file (ld --section-ordering-file, see CMakeLists.txt) that puts the
functions called at least --min times first, hottest first.

Input: calls.txt dumps of an FF_CALLCOUNT build (runtime/src/profile.c), one per
scene; a function's count is its largest over the dumps.

usage: tools/recomp/hot.py --min 1000 calls_bedroom.txt calls_street.txt ...
       (writes tools/recomp/hot_order.ld)
"""
import argparse
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('dumps', nargs='+')
    ap.add_argument('--min', type=int, default=1000)
    ap.add_argument('--out', default=os.path.join(HERE, 'hot_order.ld'))
    args = ap.parse_args()
    calls = {}
    for p in args.dumps:
        with open(p) as f:
            for line in f:
                parts = line.split()
                if len(parts) == 2:   # (a dump written while the game exits can repeat lines)
                    a, n = parts[0].upper(), int(parts[1])
                    calls[a] = max(calls.get(a, 0), n)
    hot = sorted(((n, a) for a, n in calls.items() if n >= args.min), key=lambda x: (-x[0], x[1]))
    with open(args.out, 'w') as f:
        f.write('/* Generated by tools/recomp/hot.py from %d call count dump(s), min %d calls:\n'
                '   %d hot generated functions first, hottest first. */\n.text : {\n' % (
                    len(args.dumps), args.min, len(hot)))
        for n, a in hot:
            f.write('  *(.text.f_%s)\n' % a)
        f.write('}\n')
    print('%d functions -> %s' % (len(hot), args.out))


if __name__ == '__main__':
    main()
