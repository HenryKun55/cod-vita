"""Generate shim/src/opengl32_gen.c: the gl* entry points the game looks up.

The game loads opengl32.dll itself and asks GetProcAddress / wglGetProcAddress for
every function (Quake 3's QGL). Each name it may ask for (the strings in CoDSP.exe)
gets a host function with the guest's stdcall convention: it reads the arguments
from the guest stack, turns guest pointers into host pointers and calls the real
GL function, resolved at run time (platform_gl_proc). Prototypes come from the
macOS SDK's gl.h / glext.h; names without a prototype there are left out
(GetProcAddress returns 0, as for a missing extension).

The output is checked in, so builds (the Vita's too) do not need the headers.

Usage: python3 tools/gen_gl.py gamedata/pc/CoDSP.exe [SDK_HEADERS_DIR]
"""
import os
import re
import subprocess
import sys

# Implemented by hand in shim/src/opengl32.c.
MANUAL = {'glGetString', 'glViewport', 'glScissor', 'glLockArraysEXT', 'glUnlockArraysEXT', 'glReadPixels',
          'glTexImage2D', 'glCompressedTexImage2D', 'glCompressedTexImage2DARB', 'glCompressedTexSubImage2D',
          'glCompressedTexSubImage2DARB'}

INT_TYPES = {'GLenum', 'GLboolean', 'GLbitfield', 'GLbyte', 'GLshort', 'GLint', 'GLsizei', 'GLubyte', 'GLushort',
             'GLuint', 'GLhandleARB', 'GLintptr', 'GLsizeiptr', 'GLintptrARB', 'GLsizeiptrARB', 'GLchar',
             'GLcharARB'}
FLOAT_TYPES = {'GLfloat', 'GLclampf'}
DOUBLE_TYPES = {'GLdouble', 'GLclampd'}


def parse_headers(hdir):
    protos = {}
    pat = re.compile(r'\bextern\s+([\w\s\*]+?)\s*\b(gl[A-Z]\w*)\s*\(([^)]*)\)')
    for fn in ('gl.h', 'glext.h'):
        text = re.sub(r'\s+', ' ', open(os.path.join(hdir, fn)).read())
        for m in pat.finditer(text):
            ret, name, args = m.groups()
            protos.setdefault(name, (ret.strip(), args.strip()))
    return protos


def split_arg(a):
    """('kind', c_type) of one parameter: int, float, double or ptr."""
    a = re.sub(r'\b(const|GLAPIENTRY|APIENTRY)\b', ' ', a).strip()
    if '*' in a:
        if a.count('*') > 1:
            return None
        return 'ptr', None
    t = a.split()[0]
    t = {'GLsizeiptrARB': 'GLsizeiptr', 'GLintptrARB': 'GLintptr', 'GLhandleARB': 'GLuint',
         'GLcharARB': 'GLchar'}.get(t, t)   # (vitaGL has only the core names)
    if t in INT_TYPES:
        return 'int', t
    if t in FLOAT_TYPES:
        return 'float', t
    if t in DOUBLE_TYPES:
        return 'double', t
    return None


def gen_func(name, ret, args):
    params = [] if args in ('', 'void') else [x.strip() for x in args.split(',')]
    kinds = [split_arg(p) for p in params]
    if any(k is None for k in kinds):
        return None, 'argument type'
    ret = re.sub(r'\bconst\b', '', ret).strip()
    if ret == 'void':
        rkind = 'void'
    elif ret in INT_TYPES:
        rkind = 'int'
    else:
        return None, 'return type %s' % ret
    ctypes, vals, slot = [], [], 0
    for kind, t in kinds:
        if kind == 'int':
            ctypes.append(t)
            vals.append('(%s)ARG(%d)' % (t, slot))
            slot += 1
        elif kind == 'float':
            ctypes.append('GLfloat')
            vals.append('argf(c, %d)' % slot)
            slot += 1
        elif kind == 'double':
            ctypes.append('GLdouble')
            vals.append('argd(c, %d)' % slot)
            slot += 2
        else:
            ctypes.append('void *')
            vals.append('gptr(ARG(%d))' % slot)
            slot += 1
    proto = ', '.join(ctypes) or 'void'
    rt = 'void' if rkind == 'void' else 'GLuint'
    lines = ['typedef %s (*pfn_%s)(%s);' % (rt, name, proto),
             'static pfn_%s p_%s;' % (name, name),
             'static void gl_%s(Ctx *c)' % name,
             '{']
    call = 'p_%s(%s)' % (name, ', '.join(vals))
    if rkind == 'void':
        lines.append('    %s;' % call)
        lines.append('    GL_TRACE("%s");' % name)
        lines.append('    stdcall_ret(c, c->r[0], %d);' % slot)
    else:
        lines.append('    uint32_t r = (uint32_t)%s;' % call)
        lines.append('    GL_TRACE("%s");' % name)
        lines.append('    stdcall_ret(c, r, %d);' % slot)
    lines.append('}')
    return '\n'.join(lines), None


def main():
    exe = sys.argv[1]
    hdir = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        subprocess.check_output(['xcrun', '--show-sdk-path'], text=True).strip(),
        'System/Library/Frameworks/OpenGL.framework/Headers')
    data = open(exe, 'rb').read()
    names = sorted(set(n.decode() for n in re.findall(rb'(?<![A-Za-z0-9_])(gl[A-Z][A-Za-z0-9]+)\0', data)))
    protos = parse_headers(hdir)
    out = ['/* Generated by tools/gen_gl.py - do not edit.',
           ' * The gl* functions the game can look up: guest stdcall -> host GL (opengl32.c). */',
           '#include "opengl32.h"', '']
    table = []
    skipped = []
    for n in names:
        if n in MANUAL:
            table.append((n, 'glm_%s' % n, None))
            continue
        p = protos.get(n)
        if p is None and n[-3:] in ('ARB', 'EXT'):
            p = protos.get(n[:-3])   # same function as the core one (resolved by either name)
        if p is None:
            skipped.append((n, 'no prototype'))
            continue
        body, why = gen_func(n, *p)
        if body is None:
            skipped.append((n, why))
            continue
        out.append(body)
        out.append('')
        table.append((n, 'gl_%s' % n, n))
    for n, fn, _ in table:
        if fn.startswith('glm_'):
            out.insert(4, 'void %s(Ctx *c);' % fn)
    out.append('const GlEntry g_gl_entries[] = {')
    for n, fn, host in table:
        ptr = '(void **)&p_%s' % n if host else 'NULL'
        out.append('    { "%s", %s, %s },' % (n, fn, ptr))
    out.append('};')
    out.append('const unsigned g_gl_entry_count = %d;' % len(table))
    out.append('')
    out.append('/* Not provided (no prototype or an unsupported argument type):')
    for n, why in skipped:
        out.append(' *   %s (%s)' % (n, why))
    out.append(' */')
    path = os.path.join(os.path.dirname(__file__), '..', 'shim', 'src', 'opengl32_gen.c')
    open(path, 'w').write('\n'.join(out) + '\n')
    print('%d entry points, %d left out' % (len(table), len(skipped)))


if __name__ == '__main__':
    main()
